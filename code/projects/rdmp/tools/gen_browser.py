HEAD = open("ui/native/Main.sc", encoding="utf-8").readline()
N = 24
rows = []
for i in range(N):
    rows.append(f'''      <UIList id="RdmpSrv_{i}" horizontal="true" scrollable="false" allowInput="false">
        <transition event="@UI.ACCEPT*RELEASED" consume="true">
          <action expr="PlaySound('HUD_MENU_SELECT_MASTER')"></action>
          <action expr="SendEvent('rdmp.join.{i}')"></action>
        </transition>
        <transition event="@UI.ACTION_1*RELEASED" consume="true">
          <action expr="SendEvent('rdmp.favorite.{i}')"></action>
        </transition>
        <UILabel id="RdmpSrvName_{i}" text="Common_Null"></UILabel>
        <UILabel id="RdmpSrvInfo_{i}" text="Common_Null"></UILabel>
      </UIList>''')
tabs = []
for key, ev in [("Internet", "internet"), ("Local", "local"), ("Favorites", "favorites"), ("Recent", "recent")]:
    tabs.append(f'''      <UILabel id="RdmpTab_{key}" text="Common_Null">
        <onfocused expr="SendEvent('rdmp.tab.{ev}')"></onfocused>
        <onfocused expr="activate(RdmpServerList)"></onfocused>
        <onfocused expr="show(RdmpServerList)"></onfocused>
        <onfocused expr="Enter(RdmpTabsPrompts)"></onfocused>
        <onunfocused expr="Exit(RdmpTabsPrompts)"></onunfocused>
        <transition event="@UI.ACCEPT*RELEASED" consume="true">
          <action expr="focus(RdmpServerList)"></action>
          <action expr="Unfocus(RdmpTabs)"></action>
          <action expr="Exit(RdmpTabsPrompts)"></action>
          <action expr="Enter(RdmpListPrompts)"></action>
          <action expr="SendEvent('AUDIO_StartMenuItemSelected')"></action>
        </transition>
      </UILabel>''')
body = '''  <!--
    Server browser (Red Dead Multiplayer), in the game's UI language. Generated by tools/gen_browser.py.
    It lives in the pause scene like the game's Options and uses the same pieces: the category list on the left
    (pause_main menu slot), a scrollable list of rows (list movie), prompt strips. Rows are a fixed pool: the mod sets
    their texts and hides unused ones (src/game/uifiles.cpp); their actions raise rdmp.* UI events the mod handles.
  -->
  <UILayer id="RdmpBrowser">
    <onfocused expr="StreamMovie('list')"></onfocused>
    <onunfocused expr="UnstreamMovie('list')"></onunfocused>
    <onfocused expr="SetFlashInt('pause_main','pausetransition.visibility',1)"></onfocused>
    <onfocused expr="SetFlashInt('pause_main','pausetransition.type',9)"></onfocused>
    <onunfocused expr="SetFlashInt('pause_main','pausetransition.visibility',0)"></onunfocused>
    <onactivate expr="Enter(RdmpHeader)"></onactivate>
    <ondeactivate expr="Exit(RdmpHeader)"></ondeactivate>
    <onfocused expr="Enter(RdmpTabs)"></onfocused>
    <onfocused expr="SendEvent('rdmp.browser.open')"></onfocused>
    <onunfocused expr="Exit(RdmpTabsPrompts)"></onunfocused>
    <onunfocused expr="Exit(RdmpListPrompts)"></onunfocused>
    <onunfocused expr="Unfocus(RdmpServerList)"></onunfocused>

    <transition event="@UI.CANCEL*RELEASED" consume="true">
      <action expr="PlaySound('HUD_MENU_BACK_MASTER')"></action>
      <action expr="Exit(RdmpBrowser)"></action>
      <action expr="focus(PauseMenu)"></action>
      <action expr="Enter(PauseMenu_Main_Prompts)"></action>
    </transition>

    <UILabel id="RdmpHeader" movie="list" flashObject="top_title" text="Common_Null"></UILabel>

    <UIList id="RdmpTabs" AllowWrap="true" movie="pause_main" flashObject="menu.elements[0]" consume="true" allowMouseHoverSelect="true" allowMouseAutoSelect="true">
TABS
    </UIList>

    <UIScrollableList id="RdmpServerList" MaxHeight="13" vertical="true" scrollable="true" movie="list" consume="true" allowScrollbar="true" allowMouseAutoSelect="true">
      <transition event="@UI.CANCEL*RELEASED" consume="true">
        <action expr="PlaySound('HUD_MENU_BACK_MASTER')"></action>
        <action expr="unfocus(RdmpServerList)"></action>
        <action expr="Focus(RdmpTabs)"></action>
        <action expr="Exit(RdmpListPrompts)"></action>
        <action expr="Enter(RdmpTabsPrompts)"></action>
      </transition>
      <transition event="@UI.ACTION_2*RELEASED" consume="true">
        <action expr="SendEvent('rdmp.refresh')"></action>
      </transition>
ROWS
    </UIScrollableList>

    <UIPromptStrip id="RdmpTabsPrompts" flashObject="_global.prompt">
      <UIButton icon="{@UI.ACCEPT}" text="Common_Select"></UIButton>
      <UIButton icon="{@UI.CANCEL}" text="Common_Back"></UIButton>
      <UIButton icon="{@UI.NAVIGATE_UP}{@UI.NAVIGATE_DOWN}" text="Common_Scroll"></UIButton>
    </UIPromptStrip>

    <UIPromptStrip id="RdmpListPrompts" flashObject="_global.prompt">
      <UIButton id="RdmpPrompt_Join" icon="{@UI.ACCEPT}" text="Common_Null"></UIButton>
      <UIButton id="RdmpPrompt_Favorite" icon="{@UI.ACTION_1}" text="Common_Null"></UIButton>
      <UIButton id="RdmpPrompt_Refresh" icon="{@UI.ACTION_2}" text="Common_Null"></UIButton>
      <UIButton icon="{@UI.CANCEL}" text="Common_Back"></UIButton>
    </UIPromptStrip>
  </UILayer>
</scxml>
'''
body = body.replace("TABS", "\n".join(tabs)).replace("ROWS", "\n".join(rows))
open("ui/native/Browser.sc", "w", encoding="utf-8", newline="\n").write(HEAD + body)
print("ok")
