    // Accepts "BLIP_OBJECTIVE", "blip_objective" or "objective". 0 = unknown.
    inline uint16_t BlipIconFromName(const char *name) {
        if (!name || !*name) {
            return 0;
        }
        char up[96] = "BLIP_";
        size_t n = 5;
        const char *src = name;
        if ((src[0] == 'b' || src[0] == 'B') && (src[1] == 'l' || src[1] == 'L') && (src[2] == 'i' || src[2] == 'I') &&
            (src[3] == 'p' || src[3] == 'P') && src[4] == '_') {
            src += 5;
        }
        for (; *src && n + 1 < sizeof(up); ++src) {
            up[n++] = (*src >= 'a' && *src <= 'z') ? static_cast<char>(*src - 'a' + 'A') : *src;
        }
        up[n] = 0;
        for (const auto &icon : kBlipIcons) {
            if (std::strcmp(icon.name, up) == 0) {
                return icon.id;
            }
        }
        return 0;
    }
